"""Generate src/engine/GeneratedTables.h from the Python reference constants.

Python is the single source of truth for the K-weighting prototype parameters and the
BS.1770 Annex 2 interpolation filter; the C++ engine includes the generated header.
`--check` exits non-zero if the committed header is out of date (used by the test suite).
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from ada_core import kweight, true_peak

HEADER = Path(__file__).resolve().parents[2] / "src" / "engine" / "GeneratedTables.h"


def render() -> str:
    rows = ",\n".join(
        "    { " + ", ".join(repr(float(v)) for v in row) + " }" for row in true_peak.ANNEX2_TABLE)
    constants = {
        "shelfF0": kweight.SHELF_F0,
        "shelfGainDB": kweight.SHELF_GAIN_DB,
        "shelfQ": kweight.SHELF_Q,
        "shelfVbExponent": kweight.SHELF_VB_EXP,
        "highpassF0": kweight.HIGHPASS_F0,
        "highpassQ": kweight.HIGHPASS_Q,
    }
    const_lines = "\n".join(f"inline constexpr double {k} = {float(v)!r};" for k, v in constants.items())
    return f"""// Generated by python/tools/gen_cpp_tables.py from ada_core. Do not edit by hand.
#pragma once

namespace ada::tables
{{

// K-weighting analog prototype parameters (ada_core/kweight.py, spec 3.2)
{const_lines}

// BS.1770 Annex 2 interpolation filter: row j, column p = h[4j + p]; column p is polyphase
// branch p (ada_core/true_peak.py, spec 3.3)
inline constexpr int annex2Rows = {true_peak.ANNEX2_TABLE.shape[0]};
inline constexpr int annex2Phases = {true_peak.ANNEX2_TABLE.shape[1]};
inline constexpr double annex2[annex2Rows][annex2Phases] = {{
{rows}
}};

// Interpolated outputs are attributed to input time k - interpolatorDelay
inline constexpr int interpolatorDelay = {true_peak.INTERPOLATOR_DELAY};

}} // namespace ada::tables
"""


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--check", action="store_true", help="verify the header is up to date")
    args = p.parse_args(argv)
    text = render()
    if args.check:
        current = HEADER.read_text(encoding="utf-8") if HEADER.exists() else ""
        if current != text:
            print(f"{HEADER} is out of date; run python/tools/gen_cpp_tables.py", file=sys.stderr)
            return 1
        return 0
    HEADER.parent.mkdir(parents=True, exist_ok=True)
    HEADER.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {HEADER}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
